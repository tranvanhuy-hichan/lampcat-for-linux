#!/usr/bin/env bash
# One-time (idempotent) setup. Safe to re-run; it never overwrites your files.
# Needs on the system: apache2, libapache2-mod-php, php-mysql, mariadb-server, a JDK.
set -eu
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PMA_VERSION="${PMA_VERSION:-5.2.3}"
TOMCAT_VERSION="${TOMCAT_VERSION:-10.1.61}"
say() { printf '\n== %s\n' "$*"; }

[ -f "$ROOT/config.env" ] || printf '# Shared web root for Apache (PHP) and Tomcat (JSP/Servlet)\nWEB_ROOT=www\n' > "$ROOT/config.env"
mkdir -p "$ROOT"/{www,apache/{conf/extra,logs,run},php,mysql/{logs,run,tmp},tmp/{sessions,uploads,phpmyadmin},panel,lib}
chmod +x "$ROOT/lampcat.sh"

say "Apache modules"
[ -e "$ROOT/apache/modules" ] || ln -s /usr/lib/apache2/modules "$ROOT/apache/modules"
PHP_SO="$(ls /usr/lib/apache2/modules/libphp*.so 2>/dev/null | head -n1 || true)"
[ -n "$PHP_SO" ] || { echo "mod_php not found: sudo apt install libapache2-mod-php php-mysql"; exit 1; }
sed -i "s#modules/libphp[0-9.]*\.so#modules/$(basename "$PHP_SO")#" "$ROOT/apache/conf/httpd.conf"
echo "using $(basename "$PHP_SO")"

say "php.ini"
if [ ! -f "$ROOT/php/php.ini" ]; then
  SRC="$(ls /etc/php/*/apache2/php.ini | tail -n1)"
  cp "$SRC" "$ROOT/php/php.ini"
  sed -i \
    -e 's#^;\?session.save_path *=.*#session.save_path = "${XROOT}/tmp/sessions"#' \
    -e 's#^;\?upload_tmp_dir *=.*#upload_tmp_dir = "${XROOT}/tmp/uploads"#' \
    -e 's#^;\?error_log *=.*#error_log = "${XROOT}/apache/logs/php_error.log"#' \
    -e 's#^display_errors *=.*#display_errors = On#' \
    -e 's#^error_reporting *=.*#error_reporting = E_ALL \& ~E_DEPRECATED \& ~E_STRICT#' \
    "$ROOT/php/php.ini"
  echo "created php/php.ini from $SRC"
else echo "php/php.ini exists"; fi

# "localhost" in mysqli/PDO must reach THIS stack's MariaDB, not the system one (its socket is
# /run/mysqld/mysqld.sock). Only fills the setting when it is still empty, so edits are kept.
sed -i -e 's#^mysqli.default_socket *=[ \t]*$#mysqli.default_socket = "${XROOT}/mysql/run/mysqld.sock"#' \
       -e 's#^pdo_mysql.default_socket *=[ \t]*$#pdo_mysql.default_socket = "${XROOT}/mysql/run/mysqld.sock"#' "$ROOT/php/php.ini"

say "phpMyAdmin $PMA_VERSION"
[ -d "$ROOT/htdocs/phpmyadmin" ] && [ ! -e "$ROOT/phpmyadmin" ] && mv "$ROOT/htdocs/phpmyadmin" "$ROOT/phpmyadmin"
if [ ! -f "$ROOT/phpmyadmin/index.php" ]; then
  T="$(mktemp -d)"
  if [ -n "${PMA_TGZ:-}" ] && [ -f "$PMA_TGZ" ]; then cp "$PMA_TGZ" "$T/pma.tgz"   # bundled by the .deb
  else curl -fL "https://files.phpmyadmin.net/phpMyAdmin/$PMA_VERSION/phpMyAdmin-$PMA_VERSION-all-languages.tar.gz" -o "$T/pma.tgz"; fi
  tar xzf "$T/pma.tgz" -C "$T"
  mv "$T"/phpMyAdmin-*/ "$ROOT/phpmyadmin"
  rm -rf "$T"
fi
if [ ! -f "$ROOT/phpmyadmin/config.inc.php" ]; then
  SECRET="$(head -c 24 /dev/urandom | base64 | tr -d '/+=' | head -c 32)"
  cat > "$ROOT/phpmyadmin/config.inc.php" <<EOF
<?php
// Generated by setup.sh. Local development convenience: log in as root with no password (this server only accepts local connections).
\$cfg['blowfish_secret'] = '$SECRET';
\$root = dirname(__DIR__);
// Port is read from mysql/my.cnf so the panel can change it in one place.
\$ini  = @parse_ini_file(\$root . '/mysql/my.cnf', true, INI_SCANNER_RAW);
\$port = \$ini['mysqld']['port'] ?? 3306;
\$i = 1;
\$cfg['Servers'][\$i]['auth_type'] = 'config';
\$cfg['Servers'][\$i]['host'] = '127.0.0.1';
\$cfg['Servers'][\$i]['port'] = (string) \$port;
\$cfg['Servers'][\$i]['user'] = 'root';
\$cfg['Servers'][\$i]['password'] = '';
\$cfg['Servers'][\$i]['AllowNoPassword'] = true;
\$cfg['TempDir'] = \$root . '/tmp/phpmyadmin';
EOF
fi

say "Tomcat $TOMCAT_VERSION"
if [ ! -x "$ROOT/tomcat/bin/catalina.sh" ]; then
  TGZ="${TOMCAT_TGZ:-$HOME/Downloads/apache-tomcat-$TOMCAT_VERSION.tar.gz}"
  [ -f "$TGZ" ] || { TGZ="$(mktemp -d)/tomcat.tgz"
    curl -fL "https://archive.apache.org/dist/tomcat/tomcat-10/v$TOMCAT_VERSION/bin/apache-tomcat-$TOMCAT_VERSION.tar.gz" -o "$TGZ"; }
  mkdir -p "$ROOT/tomcat"
  tar xzf "$TGZ" -C "$ROOT/tomcat" --strip-components=1
  chmod +x "$ROOT"/tomcat/bin/*.sh
else echo "tomcat exists"; fi
# Tomcat's bundled sample apps (docs, examples, manager...) are not used: your code lives in the web root.
rm -rf "$ROOT"/tomcat/webapps/{ROOT,docs,examples,manager,host-manager}
# Show a folder listing when a folder has no index file (Apache does it, Tomcat is off by default).
sed -i '/<param-name>listings<\/param-name>/{n;s/false/true/}' "$ROOT/tomcat/conf/web.xml"
# Tomcat shares the web root with Apache, so it must not serve PHP source code as text.
if ! grep -qE '(xampp-linux|lampcat): block php' "$ROOT/tomcat/conf/web.xml"; then
  sed -i 's#</web-app>#  <!-- lampcat: block php -->\n  <security-constraint>\n    <web-resource-collection>\n      <web-resource-name>php</web-resource-name>\n      <url-pattern>*.php</url-pattern>\n      <url-pattern>*.phtml</url-pattern>\n    </web-resource-collection>\n    <auth-constraint/>\n  </security-constraint>\n</web-app>#' "$ROOT/tomcat/conf/web.xml"
  echo "patched tomcat/conf/web.xml"
fi

say "MariaDB data directory"
# Ubuntu's AppArmor profile only lets /usr/sbin/mariadbd write to /var/lib/mysql, so the
# project runs its own copy of the binary (same program, different path = not confined).
mkdir -p "$ROOT/mysql/base/sbin"
cp -f /usr/sbin/mariadbd "$ROOT/mysql/base/sbin/mariadbd"
ln -sfn /usr/share "$ROOT/mysql/base/share"; ln -sfn /usr/bin "$ROOT/mysql/base/bin"; ln -sfn /usr/lib "$ROOT/mysql/base/lib"
if [ ! -d "$ROOT/mysql/data/mysql" ]; then
  rm -rf "$ROOT/mysql/data"
  mariadb-install-db --no-defaults --basedir="$ROOT/mysql/base" --datadir="$ROOT/mysql/data" \
    --auth-root-authentication-method=normal --skip-test-db >"$ROOT/mysql/logs/install.log" 2>&1 \
    && echo "initialised (root, empty password)" || { cat "$ROOT/mysql/logs/install.log"; exit 1; }
else echo "mysql/data exists"; fi

say "Done"
echo "Start:  $ROOT/lampcat.sh all start      Panel: python3 $ROOT/panel/lampcat-panel.py"
